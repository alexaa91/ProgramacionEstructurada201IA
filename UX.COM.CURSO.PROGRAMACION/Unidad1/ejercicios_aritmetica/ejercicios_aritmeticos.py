def mostrar_operadores():
    # SUMA
    suma = 5 + 3
    print("Suma 5 + 3 =", suma)
    # RESTA
    resta = 5 - 3
    print("Resta 5 + 3 =", resta)
    # MULTIPLICACION
    multiplicacion = 6 * 2
    print("multiplicacion 6 * 2 =", multiplicacion)
    # DIVISION ENTEROS
    division = 10 // 3
    print("Division 10 // 3 =", division)
    # MODULO 
    modulo = 10 % 3
    print("Modulo 10 % 3 =", modulo)
    # POTENCIACION
    potenciacion = 2 ** 3
    print("Potencia 2 ** 3 =", potenciacion)

def main():
    mostrar_operadores()

if __name__=="__main__":
    main()